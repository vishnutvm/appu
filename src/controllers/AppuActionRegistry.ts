export class AppuActionRegistry {
  public static getAll(): AppuActionDefinition[] {
    return Object.values(APPU_ACTIONS);
  }

  public static getById(id: AppuActionId | string): AppuActionDefinition | undefined {
    return (APPU_ACTIONS as Record<string, AppuActionDefinition>)[id];
  }

  public static getByCategory(category: ActionCategory): AppuActionDefinition[] {
    return Object.values(APPU_ACTIONS).filter((a) => a.category === category);
  }

  public static isGroundPose(actionId: string): boolean {
    const act = this.getById(actionId);
    return act ? act.isGroundPose : false;
  }

  public static isSleeping(actionId: string): boolean {
    return (
      actionId === 'sleep' ||
      actionId === 'deep_sleep' ||
      actionId === 'sleep_side'
    );
  }

  public static isSitting(actionId: string): boolean {
    return (
      actionId === 'sit' ||
      actionId === 'sit_relaxed' ||
      actionId === 'sit_legs_extended' ||
      actionId === 'sit_cross_legged'
    );
  }
}
